#!/usr/bin/env node
// Builds the table of enchant spells and the scroll each one makes on an Enchanting Vellum
// (src/Tradewright/src/data/Tradewright_EnchantScrollData.lua).
//
// The game's own SpellEffect table states it: an "enchant item" effect names, as its item type, the
// scroll created when the target is a vellum. The table is read from the wago.tools export of the
// client's data files. Enchants with crafting quality (Dragonflight and later) name no scroll there;
// the game reports their scrolls as ordinary recipe outputs, so they need no entry.
//
//   node scripts/build-enchant-scroll-data.mjs                  # latest retail build
//   node scripts/build-enchant-scroll-data.mjs --build 11.2.7.64978
//   node scripts/build-enchant-scroll-data.mjs --csv SpellEffect.csv   # an already downloaded export

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(ROOT, "src", "Tradewright", "src", "data", "Tradewright_EnchantScrollData.lua");
const EXPORT_URL = "https://wago.tools/db2/SpellEffect/csv";
const ENCHANT_ITEM_EFFECT = 53;

function optionValue(args, name) {
  const index = args.indexOf(name);
  return index >= 0 ? args[index + 1] : undefined;
}

async function readExport(args) {
  const file = optionValue(args, "--csv");
  if (file) return fs.readFileSync(file, "utf8");
  const build = optionValue(args, "--build");
  const url = build ? `${EXPORT_URL}?build=${encodeURIComponent(build)}` : EXPORT_URL;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.text();
}

// Every column of SpellEffect is a number, so a line splits on commas without quoting rules.
function scrollBySpell(csv) {
  const lines = csv.split(/\r?\n/).filter((line) => line !== "");
  const header = lines[0].split(",");
  const column = (name) => {
    const index = header.indexOf(name);
    if (index < 0) throw new Error(`SpellEffect export has no column ${name}`);
    return index;
  };
  const [effect, itemType, spell] = [column("Effect"), column("EffectItemType"), column("SpellID")];
  const scrolls = new Map();
  for (const line of lines.slice(1)) {
    const cells = line.split(",");
    if (cells.length !== header.length) throw new Error(`Unexpected SpellEffect row: ${line}`);
    const scrollItemID = Number(cells[itemType]);
    if (Number(cells[effect]) !== ENCHANT_ITEM_EFFECT || !(scrollItemID > 0)) continue;
    const spellID = Number(cells[spell]);
    if (scrolls.has(spellID) && scrolls.get(spellID) !== scrollItemID) {
      throw new Error(`Spell ${spellID} names two scrolls: ${scrolls.get(spellID)} and ${scrollItemID}`);
    }
    scrolls.set(spellID, scrollItemID);
  }
  return scrolls;
}

function luaSource(scrolls) {
  const rows = [...scrolls.keys()].sort((a, b) => a - b).map((spellID) => `\t[${spellID}] = ${scrolls.get(spellID)},`);
  return [
    "local _, Tradewright = ...",
    "",
    "-- The scroll each enchant makes when cast on an Enchanting Vellum: [enchant spell id] = scroll item id.",
    "-- Taken from the game's own SpellEffect table. Enchants with crafting quality are not listed; the",
    "-- game reports their scrolls as recipe outputs.",
    "-- Generated by scripts/build-enchant-scroll-data.mjs (npm run enchants:build); do not edit by hand.",
    "Tradewright.ENCHANT_SCROLL_DATA = {",
    ...rows,
    "}",
    "",
  ].join("\n");
}

const scrolls = scrollBySpell(await readExport(process.argv.slice(2)));
if (!scrolls.size) {
  console.error("No enchant names a scroll in this export; the data file is left as it was.");
  process.exit(1);
}
fs.writeFileSync(OUTPUT, luaSource(scrolls));
console.log(`${scrolls.size} enchants written to ${path.relative(ROOT, OUTPUT)}`);
