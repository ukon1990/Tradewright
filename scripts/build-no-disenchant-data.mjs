#!/usr/bin/env node
// Builds the list of gear that cannot be disenchanted
// (src/Tradewright/src/data/Tradewright_NoDisenchantData.lua).
//
// The game marks such items with a flag in its ItemSparse table; the tooltip does not show it (the
// wands an enchanter makes carry it, for one). The tables are read from the wago.tools export of
// the client's data files: Forever first, then Classic Era for the items Forever's export leaves out
// (it lacks many items the client still has). Only weapons and armor of uncommon, rare and epic
// quality are kept, the only items disenchanting would otherwise take.
//
//   node scripts/build-no-disenchant-data.mjs
//   node scripts/build-no-disenchant-data.mjs --forever-build 1.60.1.71139 --era-build 1.15.9.70576

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(ROOT, "src", "Tradewright", "src", "data", "Tradewright_NoDisenchantData.lua");
const BUILDS_URL = "https://wago.tools/api/builds";
const FLAG_NO_DISENCHANT = 0x8000;
const WEAPON_CLASS = 2;
const ARMOR_CLASS = 4;
const DISENCHANTED_QUALITY = new Set([2, 3, 4]);
const IDS_PER_LINE = 8;

function optionValue(args, name) {
  const index = args.indexOf(name);
  return index >= 0 ? args[index + 1] : undefined;
}

async function fetchText(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  return response.text();
}

async function latestBuild(product) {
  const builds = JSON.parse(await fetchText(BUILDS_URL));
  const version = builds[product]?.[0]?.version;
  if (!version) throw new Error(`wago.tools lists no build of ${product}`);
  return version;
}

// Item names hold commas and quotes, so the export is read with quoting rules.
function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (quoted) {
      if (char === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (char === '"') quoted = false;
      else cell += char;
    } else if (char === '"') quoted = true;
    else if (char === ",") { row.push(cell); cell = ""; }
    else if (char === "\n" || char === "\r") {
      if (char === "\r" && text[i + 1] === "\n") i++;
      row.push(cell); rows.push(row); row = []; cell = "";
    } else cell += char;
  }
  if (cell !== "" || row.length) { row.push(cell); rows.push(row); }
  return rows.filter((cells) => cells.length > 1);
}

// The rows of a table as objects holding only the named columns.
function readTable(csv, columns) {
  const [header, ...rows] = parseCsv(csv);
  const indexes = columns.map((name) => {
    const index = header.indexOf(name);
    if (index < 0) throw new Error(`Export has no column ${name}`);
    return index;
  });
  return rows.map((cells) => Object.fromEntries(columns.map((name, n) => [name, Number(cells[indexes[n]])])));
}

// `{ [itemID]: whether the item is gear that cannot be disenchanted }` for every item one build's export has.
async function flagsOfBuild(build) {
  const query = `?build=${encodeURIComponent(build)}`;
  const items = readTable(await fetchText(`https://wago.tools/db2/Item/csv${query}`), ["ID", "ClassID"]);
  const classOf = new Map(items.map((item) => [item.ID, item.ClassID]));
  const sparse = readTable(await fetchText(`https://wago.tools/db2/ItemSparse/csv${query}`), ["ID", "Flags_0", "OverallQualityID"]);
  const flags = new Map();
  for (const item of sparse) {
    const isGear = [WEAPON_CLASS, ARMOR_CLASS].includes(classOf.get(item.ID)) && DISENCHANTED_QUALITY.has(item.OverallQualityID);
    flags.set(item.ID, isGear && (item.Flags_0 & FLAG_NO_DISENCHANT) !== 0);
  }
  return flags;
}

function luaSource(itemIDs, builds) {
  const lines = [];
  for (let i = 0; i < itemIDs.length; i += IDS_PER_LINE) {
    lines.push("\t" + itemIDs.slice(i, i + IDS_PER_LINE).map((id) => `[${id}] = true,`).join(" "));
  }
  return [
    "local _, Tradewright = ...",
    "",
    "-- Gear the game will not disenchant, though its quality would allow it: [item id] = true. The game",
    "-- marks these items in its ItemSparse table and shows nothing on the tooltip.",
    `-- Taken from Forever ${builds.forever}, and Classic Era ${builds.era} for items Forever's export lacks.`,
    "-- Generated by scripts/build-no-disenchant-data.mjs (npm run nodisenchant:build); do not edit by hand.",
    "Tradewright.NOT_DISENCHANTABLE = {",
    ...lines,
    "}",
    "",
  ].join("\n");
}

const args = process.argv.slice(2);
const builds = {
  forever: optionValue(args, "--forever-build") ?? (await latestBuild("wowf")),
  era: optionValue(args, "--era-build") ?? (await latestBuild("wow_classic_era")),
};
const forever = await flagsOfBuild(builds.forever);
const era = await flagsOfBuild(builds.era);
const merged = new Map([...era, ...forever]);
const itemIDs = [...merged.keys()].filter((id) => merged.get(id)).sort((a, b) => a - b);
if (!itemIDs.length) {
  console.error("No gear is marked as not disenchantable in these exports; the data file is left as it was.");
  process.exit(1);
}
fs.writeFileSync(OUTPUT, luaSource(itemIDs, builds));
console.log(`${itemIDs.length} items written to ${path.relative(ROOT, OUTPUT)} (Forever ${builds.forever}, Classic Era ${builds.era})`);
